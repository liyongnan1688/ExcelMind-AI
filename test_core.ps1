$ErrorActionPreference = "Stop"

$ProjectRoot = $PSScriptRoot
$RunId = "core_" + (Get-Date -Format "yyyyMMdd_HHmmss")
$ArtifactsDir = Join-Path $ProjectRoot (Join-Path ".artifacts\tests" $RunId)
$ScriptsDir = Join-Path $ArtifactsDir "scripts"
New-Item -ItemType Directory -Path $ScriptsDir -Force | Out-Null

$previousScriptsOverride = [Environment]::GetEnvironmentVariable("LEE_EXCEL_SCRIPTS_DIR", "Process")
$env:LEE_EXCEL_SCRIPTS_DIR = $ScriptsDir

try {
    Add-Type -Path (Join-Path $ProjectRoot "bin\ExcelDna.Integration.dll")
    Add-Type -Path (Join-Path $ProjectRoot "bin\Microsoft.Web.WebView2.Core.dll")
    Add-Type -Path (Join-Path $ProjectRoot "bin\Microsoft.Web.WebView2.WinForms.dll")
    Add-Type -Path (Join-Path $ProjectRoot "bin\LeeExcel.dll")

    [LeeExcel.ScriptManager]::SetCustomScriptsDirForTesting($ScriptsDir)
    $effectiveScriptsDir = [LeeExcel.ScriptManager]::ScriptsDir
    if (-not [string]::Equals([IO.Path]::GetFullPath($effectiveScriptsDir), [IO.Path]::GetFullPath($ScriptsDir), [StringComparison]::OrdinalIgnoreCase)) {
        throw "测试脚本目录隔离失败: $effectiveScriptsDir"
    }

    Write-Host "=== Verify LeeExcel Core Features ===" -ForegroundColor Cyan
    Write-Host "隔离产物目录: $ArtifactsDir"
    Write-Host "隔离脚本目录: $ScriptsDir"

    # 1. Verify ScriptManager
    Write-Host "`n1. Test ScriptManager save and list..."
    $err = ""
    $vbaCode = "Sub AutoTest()`n    ActiveSheet.Range(""A1"").Value = 123`nEnd Sub"
    $ok = [LeeExcel.ScriptManager]::SaveScript("AutoTestScript", $vbaCode, "Generated by isolated core test suite", [ref]$err)

    if ($ok) {
        Write-Host "   [Pass] Script saved to isolated directory: $ScriptsDir" -ForegroundColor Green
    } else {
        throw "Script save failed: $err"
    }

    $scripts = [LeeExcel.ScriptManager]::ListScripts()
    Write-Host "   Total scripts in isolated storage: $($scripts.Count)"
    foreach ($s in $scripts) {
        Write-Host "   - Script: $($s.name) | Desc: $($s.description) | Created: $($s.createdAt)"
    }

    # 2. Verify NativeBridge dispatch
    Write-Host "`n2. Test NativeBridge dispatching..."
    $req = '{"action":"list_scripts"}'
    $res = [LeeExcel.NativeBridge]::Dispatch($req, $null)
    Write-Host "   [Pass] NativeBridge response: $res" -ForegroundColor Green

    # 3. Verify SimpleJson
    Write-Host "`n3. Test SimpleJson..."
    $testObj = [LeeExcel.SnapshotItem]@{
        id = "test_snap_1"
        timeDisplay = "10:45:00"
        fileName = "test.xlsx"
        promptSummary = "Test Summary Prompt"
    }
    $json = [LeeExcel.SimpleJson]::Serialize($testObj)
    Write-Host "   [Pass] SimpleJson serialized: $json" -ForegroundColor Green

    # 4. Verify ParseFlatObject with complex VBA containing multiple quotes
    Write-Host "`n4. Test ParseFlatObject with complex VBA..."
    $rawJsonPayload = '{"action":"execute_vba","code":"Sub RunTask()\r\n    With ws.Range(\"D23\")\r\n        .Value = 1\r\n    End With\r\n    ws.Range(\"N1\").Value = \"abc\"\r\nEnd Sub","prompt":"99乘法表"}'
    $parsedDict = [LeeExcel.SimpleJson]::ParseFlatObject($rawJsonPayload)

    if ($parsedDict.ContainsKey('code') -and $parsedDict['code'].Contains('End Sub') -and $parsedDict['code'].Contains('Range("D23")')) {
        Write-Host "   [Pass] Successfully parsed user VBA containing multiple quotes without truncation!" -ForegroundColor Green
        Write-Host "   Parsed code: $($parsedDict['code'])" -ForegroundColor Green
    } else {
        throw "ParseFlatObject failed or truncated the code"
    }

    Write-Host "`n=== ALL CORE TESTS PASSED SUCCESSFULLY! ===" -ForegroundColor Green
}
finally {
    try { [LeeExcel.ScriptManager]::ResetCustomScriptsDirForTesting() } catch { }
    if ($null -eq $previousScriptsOverride) {
        Remove-Item Env:LEE_EXCEL_SCRIPTS_DIR -ErrorAction SilentlyContinue
    } else {
        $env:LEE_EXCEL_SCRIPTS_DIR = $previousScriptsOverride
    }
}